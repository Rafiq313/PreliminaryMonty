/* SQLite schema and room corrections maintained as part of the importer. */
static const char monty_import_schema[] =
"PRAGMA foreign_keys=ON;\n"
"PRAGMA user_version=1;\n"
"CREATE TABLE IF NOT EXISTS mazes (\n"
" id INTEGER PRIMARY KEY,\n"
" slug TEXT NOT NULL UNIQUE CHECK(length(slug) BETWEEN 1 AND 80),\n"
" title TEXT NOT NULL,\n"
" is_native INTEGER NOT NULL DEFAULT 0 CHECK(is_native IN (0,1)),\n"
" format_version INTEGER NOT NULL DEFAULT 1 CHECK(format_version=1),\n"
" start_room INTEGER NOT NULL DEFAULT 0 CHECK(start_room BETWEEN 0 AND 99),\n"
" start_x INTEGER NOT NULL DEFAULT 124 CHECK(start_x BETWEEN 49 AND 199),\n"
" start_y INTEGER NOT NULL DEFAULT 184 CHECK(start_y BETWEEN 44 AND 225),\n"
" floor_offsets BLOB NOT NULL CHECK(length(floor_offsets)=10),\n"
" source_sha256 TEXT\n"
");\n"
"CREATE UNIQUE INDEX IF NOT EXISTS one_native_maze ON mazes(is_native) WHERE is_native=1;\n"
"CREATE TABLE IF NOT EXISTS rooms (\n"
" maze_id INTEGER NOT NULL REFERENCES mazes(id) ON DELETE CASCADE,\n"
" room_id INTEGER NOT NULL CHECK(room_id BETWEEN 0 AND 100),\n"
" role TEXT NOT NULL CHECK(role IN ('maze','special')),\n"
" source_address INTEGER,\n"
" PRIMARY KEY(maze_id,room_id)\n"
");\n"
"-- Ordered semantic commands, not Atari addresses or an opaque byte stream.\n"
"-- flags = upper two original bits; arguments retain drawing/actor parameters.\n"
"CREATE TABLE IF NOT EXISTS commands (\n"
" maze_id INTEGER NOT NULL,\n"
" room_id INTEGER NOT NULL,\n"
" sequence INTEGER NOT NULL CHECK(sequence>=0),\n"
" opcode INTEGER NOT NULL CHECK(opcode BETWEEN 0 AND 63),\n"
" flags INTEGER NOT NULL DEFAULT 0 CHECK(flags BETWEEN 0 AND 3),\n"
" cell_offset INTEGER CHECK(cell_offset BETWEEN 0 AND 1023),\n"
" argument1 INTEGER CHECK(argument1 BETWEEN 0 AND 255),\n"
" argument2 INTEGER CHECK(argument2 BETWEEN 0 AND 255),\n"
" reference_room INTEGER CHECK(reference_room BETWEEN 0 AND 100),\n"
" PRIMARY KEY(maze_id,room_id,sequence),\n"
" FOREIGN KEY(maze_id,room_id) REFERENCES rooms(maze_id,room_id) ON DELETE CASCADE,\n"
" FOREIGN KEY(maze_id,reference_room) REFERENCES rooms(maze_id,room_id)\n"
");\n"
"-- Optional overrides for custom labyrinths; missing exits use original coordinates.\n"
"CREATE TABLE IF NOT EXISTS exits (\n"
" maze_id INTEGER NOT NULL,\n"
" room_id INTEGER NOT NULL,\n"
" direction INTEGER NOT NULL CHECK(direction BETWEEN 0 AND 3),\n"
" destination INTEGER NOT NULL CHECK(destination BETWEEN 0 AND 99),\n"
" PRIMARY KEY(maze_id,room_id,direction),\n"
" FOREIGN KEY(maze_id,room_id) REFERENCES rooms(maze_id,room_id) ON DELETE CASCADE,\n"
" FOREIGN KEY(maze_id,destination) REFERENCES rooms(maze_id,room_id)\n"
");\n";
